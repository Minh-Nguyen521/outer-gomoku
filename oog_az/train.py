"""The learning loop: self-play -> optimise -> gate -> promote, repeated.

LOSS is the AlphaZero objective: cross-entropy against the MCTS visit
distribution, plus mean-squared error against the game outcome, plus weight
decay. The policy target is a full distribution rather than a one-hot best
move, which is the point -- the search's relative confidence across moves is
far more information than its argmax.

GATING. A new network replaces the current one only if it beats it by a margin
over a fixed number of games. Without a gate, a bad iteration is promoted and
the next round of self-play is generated by a worse player, which compounds.
arena.py additionally gates against an EXTERNAL engine, because self-play Elo
can rise while real strength does not -- this project measured exactly that:
SearchV4 won all eight self-play pairings at 80% and then scored BELOW the
untouched baseline against an outside opponent (docs/search-comparison.md
Round 7). Any improvement claimed only against yourself is not yet a result.

METRICS go to a JSONL file, never tensorboard. See net.py for why that is not
a stylistic choice.
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import sys
import time

import numpy as np
import torch
import torch.nn.functional as F

from .env import NUM_ACTIONS
from .net import AZNet, load_checkpoint, pick_device, save_checkpoint
from .selfplay import ReplayBuffer, generate, generate_parallel


def mirror(dest: str | None, run_dir: str) -> None:
    """Copy the resumable state out to durable storage (Drive, on Colab).

    WHY THIS IS NOT OPTIONAL ON COLAB. This project has already lost a
    complete MiniZero training run to a recycled VM, because nothing outside
    the VM held the checkpoints (docs/minizero.md). Training writes to LOCAL
    disk -- Drive's FUSE layer is far too slow for self-play's many small
    writes -- and this pushes the results out afterwards.

    Only the files needed to resume are copied: the net, the progress marker,
    the replay buffer and the metrics. Per-iteration snapshots are left behind
    deliberately; they are for inspection, and copying every one of them to
    Drive would dominate the transfer.

    Failures are reported, never swallowed. A sync that silently copies
    nothing is how the original run was lost, and `cp -u` being GNU-only was
    the specific mechanism.
    """
    if not dest:
        return
    try:
        os.makedirs(dest, exist_ok=True)
        for name in ("best.pt", "state.json", "buffer.npz", "metrics.jsonl"):
            src = os.path.join(run_dir, name)
            if not os.path.exists(src):
                continue
            tmp = os.path.join(dest, name + ".tmp")
            shutil.copy2(src, tmp)
            os.replace(tmp, os.path.join(dest, name))
    except Exception as exc:                      # noqa: BLE001 - must be loud
        print(f"  !! MIRROR FAILED to {dest}: {type(exc).__name__}: {exc}",
              flush=True)
        print("     checkpoints exist LOCALLY only -- do not let this VM be "
              "recycled until you have copied them out.", flush=True)


def train_steps(net, device, buffer: ReplayBuffer, steps: int, batch_size: int,
                lr: float, weight_decay: float = 1e-4,
                value_weight: float = 1.0, log_path: str | None = None):
    """Run `steps` optimisation steps. Returns a stats dict."""
    if len(buffer) < batch_size:
        return {"skipped": True, "reason": f"buffer {len(buffer)} < batch {batch_size}"}

    net.train()
    opt = torch.optim.SGD(net.parameters(), lr=lr, momentum=0.9,
                          weight_decay=weight_decay, nesterov=True)
    p_loss_sum = v_loss_sum = 0.0
    t0 = time.time()

    for _ in range(steps):
        planes, policies, values = buffer.sample(batch_size)
        x = torch.from_numpy(planes).to(device)
        target_p = torch.from_numpy(policies).to(device)
        target_v = torch.from_numpy(values).to(device)

        logits, value = net(x)
        # Cross-entropy against a full distribution: -sum(p * log q).
        log_q = F.log_softmax(logits, dim=1)
        policy_loss = -(target_p * log_q).sum(dim=1).mean()
        value_loss = F.mse_loss(value, target_v)
        loss = policy_loss + value_weight * value_loss

        opt.zero_grad(set_to_none=True)
        loss.backward()
        opt.step()

        p_loss_sum += float(policy_loss.item())
        v_loss_sum += float(value_loss.item())

    net.eval()
    stats = {
        "steps": steps,
        "policy_loss": round(p_loss_sum / steps, 4),
        "value_loss": round(v_loss_sum / steps, 4),
        "lr": lr,
        "seconds": round(time.time() - t0, 1),
    }
    if log_path:
        with open(log_path, "a") as fh:
            fh.write(json.dumps({"stage": "train", **stats}) + "\n")
    return stats


def duel(net_a, net_b, device, games: int, simulations: int,
         temp_moves: int = 4):
    """Play `games` between two networks. Returns A's score in [0, 1].

    Colours alternate every game so a first-player advantage cannot decide the
    gate. A few opening plies are sampled at temperature 1, otherwise every
    game from the same start is identical and `games` samples one game.
    """
    from .env import Board
    from .mcts import MCTS

    a = MCTS(net_a, device, simulations=simulations)
    b = MCTS(net_b, device, simulations=simulations)
    score = 0.0

    for g in range(games):
        board = Board()
        a_is_black = (g % 2 == 0)
        while not board.is_terminal() and len(board.history) < 225:
            mine = (board.turn == 0) == a_is_black
            engine = a if mine else b
            temperature = 1.0 if len(board.history) < temp_moves else 0.0
            # No Dirichlet noise when measuring: it is an exploration device
            # for data generation, and it would make the gate noisier.
            action, _ = engine.choose(board, temperature=temperature,
                                      add_noise=False)
            board.play(action)
        if board.winner is None or board.winner == -1:
            score += 0.5
        else:
            a_won = (board.winner == 0) == a_is_black
            score += 1.0 if a_won else 0.0
    return score / games


def main(argv=None) -> int:
    p = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--run-dir", default="oog_az/runs/dev")
    p.add_argument("--iterations", type=int, default=20)
    p.add_argument("--games", type=int, default=40, help="self-play games per iteration")
    p.add_argument("--simulations", type=int, default=200, help="MCTS sims per move")
    p.add_argument("--steps", type=int, default=400, help="optimisation steps per iteration")
    p.add_argument("--batch-size", type=int, default=256)
    p.add_argument("--lr", type=float, default=0.02)
    p.add_argument("--blocks", type=int, default=6)
    p.add_argument("--channels", type=int, default=96)
    p.add_argument("--buffer-capacity", type=int, default=300_000)
    p.add_argument("--gate-games", type=int, default=20)
    p.add_argument("--gate-threshold", type=float, default=0.55,
                   help="candidate must score at least this to be promoted")
    p.add_argument("--gate-sims", type=int, default=100)
    p.add_argument("--device", default=None)
    p.add_argument("--no-augment", action="store_true")
    p.add_argument("--concurrency", type=int, default=32,
                   help="self-play games advanced in lockstep, which IS the "
                        "network batch size. 1 reproduces the old serial "
                        "behaviour; 32-128 keeps a GPU busy.")
    p.add_argument("--until", type=int, default=0, metavar="N",
                   help="run until iteration N (absolute). Use this for a long "
                        "run that may be interrupted: --iterations is relative "
                        "and would extend the target every time you resume.")
    p.add_argument("--mirror-dir", default=None, metavar="DIR",
                   help="copy checkpoints, state and metrics here after every "
                        "iteration -- point it at Google Drive on Colab. "
                        "Training itself writes to local disk, because Drive's "
                        "FUSE layer is far too slow for self-play's many small "
                        "writes.")
    p.add_argument("--gumbel", action="store_true",
                   help="Gumbel root selection + completed-Q policy target "
                        "(Danihelka et al. ICLR 2022). This is what lets "
                        "training work at ~50 simulations instead of ~800, "
                        "and is the method MiniZero uses.")
    p.add_argument("--n-considered", type=int, default=16,
                   help="Gumbel: root actions sequential halving starts from")
    p.add_argument("--serial-selfplay", action="store_true",
                   help="use the one-game-at-a-time generator (debugging only)")
    cfg = p.parse_args(argv)

    os.makedirs(cfg.run_dir, exist_ok=True)
    device = pick_device(cfg.device)
    log_path = os.path.join(cfg.run_dir, "metrics.jsonl")
    best_path = os.path.join(cfg.run_dir, "best.pt")
    buffer_path = os.path.join(cfg.run_dir, "buffer.npz")
    state_path = os.path.join(cfg.run_dir, "state.json")

    print(f"device: {device}", flush=True)

    # ---- resume ---------------------------------------------------------
    # state.json, NOT the checkpoint, is the authority on how far we got.
    # best.pt's `iteration` only advances when a candidate is PROMOTED, so a
    # run that had five gates rejected and then crashed would resume five
    # iterations earlier and redo all of them -- burning hours and, worse,
    # re-filling the buffer with duplicates of data it already had.
    state = {}
    if os.path.exists(state_path):
        try:
            state = json.load(open(state_path))
        except (ValueError, OSError) as exc:
            print(f"  state.json unreadable ({exc}); starting from the "
                  f"checkpoint instead", flush=True)

    if os.path.exists(best_path):
        net, meta = load_checkpoint(best_path, device)
        start_iter = int(state.get("iteration", meta.get("iteration", 0)))
        print(f"resumed at iteration {start_iter} "
              f"(net from {os.path.basename(best_path)}, "
              f"last promotion at {meta.get('iteration', '?')})", flush=True)
    else:
        net = AZNet(cfg.blocks, cfg.channels).to(device)
        net.eval()
        start_iter = 0
        save_checkpoint(net, best_path, iteration=0)
        print(f"initialised new net ({cfg.blocks}x{cfg.channels})", flush=True)

    buffer = ReplayBuffer.load(buffer_path, cfg.buffer_capacity)
    print(f"buffer: {len(buffer)} samples", flush=True)

    def write_state(iteration: int) -> None:
        """Record progress atomically, then mirror.

        Atomic because Colab kills processes without warning: a truncated
        state.json that parses as iteration 0 would silently restart a
        300-iteration run from scratch.
        """
        tmp = state_path + ".tmp"
        with open(tmp, "w") as fh:
            json.dump({"iteration": iteration,
                       "blocks": cfg.blocks, "channels": cfg.channels,
                       "games": cfg.games, "simulations": cfg.simulations,
                       "concurrency": cfg.concurrency,
                       "updated": time.strftime("%Y-%m-%d %H:%M:%S")}, fh)
        os.replace(tmp, state_path)
        mirror(cfg.mirror_dir, cfg.run_dir)

    last = cfg.until if cfg.until else start_iter + cfg.iterations
    if last <= start_iter:
        print(f"nothing to do: already at iteration {start_iter}, "
              f"target {last}", flush=True)
        return 0
    print(f"running iterations {start_iter + 1}..{last}", flush=True)

    for it in range(start_iter + 1, last + 1):
        print(f"\n=== iteration {it} ===", flush=True)

        if cfg.serial_selfplay:
            sp = generate(net, device, cfg.games, cfg.simulations, buffer,
                          log_path=log_path, augment=not cfg.no_augment)
        else:
            sp = generate_parallel(net, device, cfg.games, cfg.simulations,
                                   buffer, concurrency=cfg.concurrency,
                                   log_path=log_path,
                                   augment=not cfg.no_augment,
                                   gumbel=cfg.gumbel,
                                   n_considered=cfg.n_considered)
        print(f"  self-play: {sp}", flush=True)
        buffer.save(buffer_path)
        # Record progress BEFORE the gate. Self-play is the expensive half;
        # if the process dies during training or gating, resuming should not
        # replay these games.
        write_state(it)

        # Train a COPY, so a failed gate costs nothing.
        candidate = AZNet(cfg.blocks, cfg.channels).to(device)
        candidate.load_state_dict(net.state_dict())
        tr = train_steps(candidate, device, buffer, cfg.steps, cfg.batch_size,
                         cfg.lr, log_path=log_path)
        print(f"  train: {tr}", flush=True)
        if tr.get("skipped"):
            continue

        score = duel(candidate, net, device, cfg.gate_games, cfg.gate_sims)
        promoted = score >= cfg.gate_threshold
        print(f"  gate: candidate scored {score:.3f} vs current "
              f"({'PROMOTED' if promoted else 'rejected'})", flush=True)
        with open(log_path, "a") as fh:
            fh.write(json.dumps({"stage": "gate", "iteration": it,
                                 "score": score, "promoted": promoted}) + "\n")

        if promoted:
            net = candidate
            save_checkpoint(net, best_path, iteration=it)
            save_checkpoint(net, os.path.join(cfg.run_dir, f"iter{it:04d}.pt"),
                            iteration=it)
        write_state(it)

    print("\ndone", flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
