#!/usr/bin/env python3
"""Amalgamate SlowRenju + the Botzone adapter into ONE .cpp for submission.

Botzone compiles a single uploaded source file. SlowRenju is 13 translation
units plus a header, and this project adds compat shims and an adapter, so
they have to be inlined in the right order.

Three things this has to get right, all of which are normally handled by
compiler flags that a single-file upload cannot carry:

  * `-D__int64='long long'` becomes a #define at the top (MSVC type).
  * `-include Windows.h` becomes: the compat shims are emitted FIRST, before
    anything that uses printf_s / Sleep / _beginthread / the clock() override.
  * `-Dmain=slowrenju_main` cannot be a global #define here, because the
    adapter needs its own main(). So the engine's main is renamed textually,
    in its file only.

GPL-3: SlowRenju is GPL-3 (Tianyi Hao). The generated file carries upstream's
attribution, and submitting source is what the licence asks for.

Usage:
    tools/make_botzone_slowrenju.py --out build/botzone_slowrenju.cpp
    c++ -std=c++17 -O2 -o /tmp/bz build/botzone_slowrenju.cpp   # verify
"""

import argparse
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SR = os.path.join(ROOT, "third_party", "SlowRenju")

INC_LOCAL = re.compile(r'^\s*#\s*include\s+"[^"]+"[^\n]*$', re.M)
INC_ANGLE_LOCAL = re.compile(r'^\s*#\s*include\s+<(Windows\.h|process\.h)>[^\n]*$', re.M)
INC_SYS = re.compile(r'^\s*#\s*include\s+<([^>]+)>[^\n]*$', re.M)

# Headers that only exist on one platform. Hoisting every #include to the top
# of the bundle lifts them OUT of the #if that guarded them, so a Linux
# compiler then sees them unconditionally -- Botzone rejected the first
# submission with "mach-o/dyld.h: No such file or directory". Re-emit these
# under their guard instead of in the plain list.
APPLE_ONLY = {"mach-o/dyld.h"}
PRAGMA_ONCE = re.compile(r'^\s*#\s*pragma\s+once\s*$', re.M)


def read(p):
    with open(p, encoding="utf-8", errors="replace") as fh:
        return fh.read()


def strip(text, keep_sys=True):
    """Remove local includes and pragma once; collect system includes."""
    sys_incs = set()
    if keep_sys:
        # Windows.h / process.h resolve to OUR shims, not system headers.
        for m in INC_SYS.finditer(text):
            if m.group(1) not in ("Windows.h", "process.h"):
                sys_incs.add(m.group(1))
    text = INC_ANGLE_LOCAL.sub("", text)
    text = INC_LOCAL.sub("", text)
    text = INC_SYS.sub("", text)
    text = PRAGMA_ONCE.sub("", text)
    return text, sys_incs


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="build/botzone_slowrenju.cpp")
    cfg = ap.parse_args(argv)

    adapter = os.path.join(ROOT, "tools", "botzone_slowrenju.cpp")
    compat = [os.path.join(SR, "compat", "Windows.h"),
              os.path.join(SR, "compat", "process.h")]
    headers = [os.path.join(SR, "Headers", "game.h")]
    engine = sorted(p for p in glob.glob(os.path.join(SR, "**", "*.cpp"),
                                         recursive=True)
                    if "Android" not in p)

    sys_incs = set()
    chunks = []

    def add(path, text, label=None):
        body, incs = strip(text)
        sys_incs.update(incs)
        chunks.append(f"\n// ===== {label or os.path.relpath(path, ROOT)} =====\n{body}")

    # 1. compat shims first -- everything below depends on them.
    for p in compat:
        add(p, read(p))
    # 2. the engine's shared header.
    for p in headers:
        add(p, read(p))
    # 3. the adapter (keeps its own main()).
    add(adapter, read(adapter))
    # 4. engine translation units; rename main() in the file that has it.
    renamed = 0
    for p in engine:
        t = read(p)
        t, n = re.subn(r'(?m)^(\s*)int\s+main\s*\(', r'\1int slowrenju_main(', t)
        renamed += n
        add(p, t)
    if renamed == 0:
        print("  WARNING: engine main() not found -- link will fail",
              file=sys.stderr)

    banner = (
        "// GENERATED by tools/make_botzone_slowrenju.py -- do not edit.\n"
        "//\n"
        "// SlowRenju 5.1.3 by Tianyi Hao (https://www.wind23.com/), GPL-3,\n"
        "// wrapped for botzone.org.cn. Strongest classical engine measured in\n"
        "// this project: 18-2 vs rapfi-nnue, 20-0 vs Rapfi-2018. No weight\n"
        "// files, ~0.04s per move, which is why it suits a sandbox that\n"
        "// compiles what you upload and allows 1s per turn.\n"
        "//\n"
        "// Local fixes carried in from third_party/SlowRenju (see\n"
        "// docs/engine-ladder.md): the BOARD handler's missing `moven` reset,\n"
        "// and a clock() shim -- MSVC's clock() is wall-clock milliseconds\n"
        "// while POSIX returns CPU microseconds, so every time budget expired\n"
        "// about 1000x early without it.\n"
        "//\n"
        "// MSVC type, normally supplied as -D__int64='long long'.\n"
        "#define __int64 long long\n")

    parts = [banner]
    apple = sorted(sys_incs & APPLE_ONLY)
    plain = sorted(sys_incs - APPLE_ONLY)
    parts.append("".join(f"#include <{h}>\n" for h in plain))
    if apple:
        parts.append("#if defined(__APPLE__)\n"
                     + "".join(f"#include <{h}>\n" for h in apple)
                     + "#endif\n")
    parts.extend(chunks)

    out = os.path.join(ROOT, cfg.out)
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w") as fh:
        fh.write("".join(parts))
    print(f"wrote {cfg.out}: {os.path.getsize(out)//1024} KB, "
          f"{len(engine)} engine sources, {len(sys_incs)} system includes, "
          f"main renamed in {renamed} file(s)", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
