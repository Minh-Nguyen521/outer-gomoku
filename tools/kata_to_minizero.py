#!/usr/bin/env python3
"""Convert KataGomo (KataGo fork) self-play games to MiniZero SGF format.

Warm-start data source for MiniZero AlphaZero training: MiniZero cannot load
KataGo weights (different architecture/features), but it CAN learn from
KataGo-generated games. MiniZero's DataLoader reads SGF where each move carries
a policy distribution tag P[id:prob,...]; for gomoku the value target is the
final result tag RE (+1 Black wins / -1 White / 0 draw) -- GomokuEnvLoader::
getValue() ignores per-move V tags and always returns getReturn().

Games are generated by KataGomo's raw network (kata-raw-nn, no search):
moves are sampled from the net's own policy. That is fast (one forward pass
per position, reused as both the move generator and the policy target) and
exactly imitation-learning data.

FIX 1 (--visits N, default 0 = raw net): plays and labels from MCTS instead.
With visits > 0 the teacher switches to `kata-analyze` and the per-move policy
tag becomes the MCTS visit distribution, with the played move sampled from
it -- the same target AlphaZero learns (post-search policy), much sharper
than the raw net at the cost of N visits per move (~0.5-2 s at N=200).

FIX 2 (--outer-open, default on): the OUTER-OPEN first-move rule is enforced
at generation time. Black's ply-0 candidate set is masked to the outer two
rows/columns before renormalising and sampling, so ply-0 labels are
ON-distribution for env_gomoku_rule=outer_open and every later position is
reached from a legal ring opening (the raw net's centre-first preference
would otherwise make all opening labels worthless). Later plies are
untouched -- freestyle itself matches the variant.

CAVEAT: the net plays FREESTYLE (overline wins), which matches our variant
setting env_gomoku_exactly_five_stones=false, but has no Outer-Open opening
theory (first move near edge). Early-ply policies are the weakest labels.

Usage:
    tools/kata_to_minizero.py \
        --katago third_party/KataGomo/cpp/build2/katago \
        --model third_party/kgweights/tworule_20x_b18.bin.gz \
        --config third_party/KataGomo/cpp/build2/oog.cfg \
        --games 20 --out data/kata_sgfs/
Then place/copy the *.sgf files into <training_dir>/sgf/<i>.sgf and let
train.py load them (they merge with self-play data in the replay buffer).
"""

import argparse
import os
import random
import re
import subprocess
import sys
import time

N = 15
LETTERS = "ABCDEFGHJKLMNOPQRSTUVWXYZ"      # GTP skips 'I'


def to_gtp(x, y):
    return f"{LETTERS[x]}{N - y}"


class KataTeacher:
    def __init__(self, katago, model, config):
        self.p = subprocess.Popen(
            [katago, "gtp", "-model", model, "-config", config],
            stdin=subprocess.PIPE, stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL, text=True, bufsize=1)
        self._cmd("boardsize 15")

    def _cmd(self, line):
        self.p.stdin.write(line + "\n")
        self.p.stdin.flush()
        out = []
        while True:
            ln = self.p.stdout.readline()
            if ln == "":
                return None
            ln = ln.rstrip("\n")
            if ln.startswith("?"):
                return None
            if ln.startswith("="):
                out.append(ln[2:] if len(ln) > 2 else "")
                break
        while True:
            ln = self.p.stdout.readline()
            if ln in ("\n", ""):
                break
            out.append(ln.rstrip("\n"))
        return out

    def raw_nn(self, moves):
        """Return (white_win, policy[N*N]) for a position given as move list,
        or (None, None). Position is replayed via play commands."""
        self._cmd("clear_board")
        for i, (x, y) in enumerate(moves):
            colour = "B" if i % 2 == 0 else "W"
            if self._cmd(f"play {colour} {to_gtp(x, y)}") is None:
                return None, None
        resp = self._cmd("kata-raw-nn 0")
        if not resp:
            return None, None
        white_win = None
        policy = []
        reading = False
        for ln in resp:
            s = ln.strip()
            if s.startswith("whiteWin"):
                white_win = float(s.split()[1])
            elif s == "policy":
                reading = True
            elif reading:
                parts = s.split()
                try:
                    float(parts[0])
                except (ValueError, IndexError):
                    reading = False
                    continue
                for v in parts:
                    f = float(v)
                    policy.append(0.0 if f != f else f)  # NaN (occupied) -> 0
        if white_win is None or len(policy) < N * N:
            return None, None
        policy = policy[:N * N]     # trailing entry = pass move
        return white_win, policy

    def analyse(self, moves, visits):
        """Return (white_win, policy[N*N]) from MCTS with ~`visits` root
        playouts via kata-analyze; the policy is the visit distribution
        (the AlphaZero-style post-search target).

        NB: analyzeAsync runs with searchFactor=1e40 in this fork, so any
        config maxVisits/maxTime is multiplied out of effect -- the visit
        budget can ONLY be enforced client-side, by watching streamed info
        lines and sending an extra input line to stop (any input stops the
        analysis and makes the engine emit a bare newline).

        All reads go through readline() (never mixing raw os.read on the
        same buffered pipe), and we always drain up to the reply of the
        stopping command so the pipe stays aligned for the next _cmd()."""
        self._cmd("clear_board")
        for i, (x, y) in enumerate(moves):
            colour = "B" if i % 2 == 0 else "W"
            if self._cmd(f"play {colour} {to_gtp(x, y)}") is None:
                return None, None
        self.p.stdin.write("kata-analyze 100\n")
        self.p.stdin.flush()
        # kata-analyze line (one per child move per report tick), e.g.:
        # info move J9 visits 6 utility 0.986690 winrate 0.993996 scoreMean ...
        mv_re = re.compile(r"^info\s+move\s+([A-O])(1[0-5]|[1-9])\b")
        kv_re = re.compile(r"(visits|winrate)\s+([0-9.]+)")
        counts = {}
        white_win = None
        deadline = time.time() + 7200
        got_ack = False
        while time.time() < deadline:
            ln = self.p.stdout.readline()
            if ln == "":
                return None, None
            s = ln.strip()
            if not s:
                continue
            if not got_ack:
                # the engine acks the command ("= ") BEFORE the first
                # info line (comment in gtp.cpp guarantees ordering)
                if s.startswith(("=", "?")):
                    got_ack = True
                    continue
                got_ack = True
            if s.startswith("?"):
                break
            if mv_re.match(s):
                kvs = dict(kv_re.findall(s))
                if "visits" not in kvs:
                    continue
                x = LETTERS.index(mv_re.match(s).group(1))
                y = N - int(mv_re.match(s).group(2))
                counts[y * N + x] = int(kvs["visits"])
                if "winrate" in kvs:
                    # winrate is from the side-to-move's perspective
                    white_win = float(kvs["winrate"])
            if counts and sum(counts.values()) >= visits:
                break
        # Stop the analysis: any input line does it. `name` replies "= KataGo".
        self.p.stdin.write("name\n")
        self.p.stdin.flush()
        while True:
            ln = self.p.stdout.readline()
            if ln == "":
                break
            if ln.startswith("= "):
                break
        return self._finish_analyse(counts, white_win, moves)

    def _finish_analyse(self, counts, white_win, moves):
        if not counts:
            return None, None
        if white_win is None:
            white_win = 0.5
        if len(moves) % 2 == 1:   # White to move: flip to Black's perspective
            white_win = 1.0 - white_win
        total = sum(counts.values())
        policy = [0.0] * (N * N)
        for aid, c in counts.items():
            policy[aid] = c / total
        return white_win, policy

    def close(self):
        try:
            self.p.stdin.write("quit\n")
            self.p.stdin.flush()
        except Exception:
            pass
        self.p.kill()


def five_at(board, x, y):
    """True if stone at (x,y) completes >=5 in a row. board[y][x] in 'BW'."""
    c = board[y][x]
    for dx, dy in ((1, 0), (0, 1), (1, 1), (1, -1)):
        cnt = 1
        for s in (1, -1):
            nx, ny = x + dx * s, y + dy * s
            while 0 <= nx < N and 0 <= ny < N and board[ny][nx] == c:
                cnt += 1
                nx += dx * s
                ny += dy * s
        if cnt >= 5:
            return True
    return False


def is_ring_square(aid):
    """True if action_id lies in the outer two rows or columns of 15x15
    (the Outer-Open legal region for Black's first move)."""
    x, y = aid % N, aid // N
    return x < 2 or x >= N - 2 or y < 2 or y >= N - 2


def play_one(teacher, rng, temperature=1.0, max_moves=N * N,
             visits=0, outer_open=True):
    """Play one game. Returns (moves, policies, values, result) with result
    +1 Black / -1 White / 0 draw and per-move values in BLACK's perspective
    (+1 Black winning) -- or (None, None, None, reason) on failure.
    visits > 0 -> MCTS moves and visit-distribution labels;
    outer_open -> Black's ply-0 candidates masked to the outer ring."""
    board = [["."] * N for _ in range(N)]
    moves, policies, values = [], [], []
    for ply in range(max_moves):
        if visits > 0:
            white_win, pol = teacher.analyse(moves, visits)
        else:
            white_win, pol = teacher.raw_nn(moves)
        if white_win is None:
            return None, None, None, ("raw_nn failed" if visits == 0
                                       else "analyse failed")
        # Enforce the outer-open rule on the sampling distribution itself so
        # ply-0 policy labels are on-distribution for the variant.
        if ply == 0 and outer_open:
            pol = [p if is_ring_square(i) else 0.0 for i, p in enumerate(pol)]
        # mask occupied (should already be 0), renormalise, sample
        legal = []
        for i, pr in enumerate(pol):
            x, y = i % N, i // N
            if board[y][x] == "." and pr > 0:
                legal.append((i, pr))
        if not legal:
            break
        if temperature > 0:
            ws = [pr ** (1.0 / temperature) for _, pr in legal]
        else:
            ws = [1.0 if _ == max(legal, key=lambda t: t[1])[0] else 0.0
                  for _ in legal]
        aid = rng.choices([i for i, _ in legal], weights=ws)[0]
        x, y = aid % N, aid // N
        board[y][x] = "B" if ply % 2 == 0 else "W"
        moves.append((x, y))
        policies.append(pol)
        # KataGomo value: teacher's P(White wins) -> Black-perspective
        values.append(1.0 - white_win)
        if five_at(board, x, y):
            return moves, policies, values, (1 if ply % 2 == 0 else -1)
    return moves, policies, values, 0


def to_sgf(moves, policies, values, result):
    """MiniZero SGF. Move = ;<B|W>[<action_id>] followed by P[...] and V[..]
    tags. action_id = row * N + col (row 0 = top, matching MiniZero
    BaseBoardAction). P = teacher policy (soft label); V = teacher value in
    Black's perspective, consumed by GomokuEnvLoader::getValue (falls back
    to game result RE when absent)."""
    sgf = f"(;GM[Gomoku]SZ[{N}]RE[{result:+.1f}]"
    for i, (x, y) in enumerate(moves):
        stm = "B" if i % 2 == 0 else "W"
        sgf += f";{stm}[{y * N + x}]"
        entries = [f"{pid}:{policies[i][pid]:.6f}"
                   for pid in range(N * N)
                   if policies[i][pid] > 1e-5]
        if entries:
            sgf += f"P[{','.join(entries)}]"
        sgf += f"KV[{values[i]:+.6f}]"
    return sgf + ")"


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--katago", required=True)
    ap.add_argument("--model", required=True)
    ap.add_argument("--config", required=True)
    ap.add_argument("--games", type=int, default=20)
    ap.add_argument("--out", required=True)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--temperature", type=float, default=1.0)
    ap.add_argument("--visits", type=int, default=0,
                    help="MCTS visits per move via kata-analyze; 0 = raw "
                         "network. Labels become visit distributions.")
    ap.add_argument("--no-outer-open", action="store_true",
                    help="disable the first-move ring mask (plain freestyle "
                         "openings; off-distribution for the variant)")
    ap.add_argument("--start-index", type=int, default=0,
                    help="first sgf filename index (for appending runs)")
    ap.add_argument("--per-iteration", type=int, default=0,
                    help="pack this many games per <out>/<i>.sgf file, "
                         "matching MiniZero's layout of one file per "
                         "training iteration (each game on its own line). "
                         "0 = one file per game (default, plain exports)")

    args = ap.parse_args(argv)

    os.makedirs(args.out, exist_ok=True)
    rng = random.Random(args.seed)
    teacher = KataTeacher(args.katago, args.model, args.config)

    results = {"B": 0, "W": 0, "draw": 0}
    written = 0
    bucket = []          # games buffered for the current iteration file
    iter_idx = args.start_index

    def flush_bucket():
        nonlocal bucket, iter_idx
        if not bucket:
            return
        out_file = os.path.join(args.out, f"{iter_idx}.sgf")
        mode = 'a' if os.path.exists(out_file) else 'w'
        with open(out_file, mode) as f:
            f.writelines(g + "\n" for g in bucket)
        bucket = []
        iter_idx += 1

    for g in range(args.games):
        ret = play_one(teacher, rng, args.temperature,
                       visits=args.visits, outer_open=not args.no_outer_open)
        if ret[0] is None:
            print(f"game {g}: FAILED ({ret[3]})", file=sys.stderr)
            continue
        moves, policies, values, result = ret
        results["B" if result == 1 else "W" if result == -1 else "draw"] += 1
        sgf = to_sgf(moves, policies, values, result)
        if args.per_iteration > 0:
            bucket.append(sgf)
            if len(bucket) >= args.per_iteration:
                flush_bucket()
        else:
            out_file = os.path.join(args.out, f"{args.start_index + written}.sgf")
            with open(out_file, 'w') as f:
                f.write(sgf + "\n")
        written += 1
        print(f"game {g}: {result:+.1f} ({len(moves)} moves)",
              file=sys.stderr, flush=True)
    flush_bucket()

    teacher.close()
    print(f"done: {written}/{args.games} games, results {results}",
          file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
